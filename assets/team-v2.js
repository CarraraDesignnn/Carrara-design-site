/* team-v2 (preview): "Made by Hand" studio section on the homepage, between the print drop and What a Commission Means.
   Inserted after the app hydrates. Photo swaps to the studio clip on hover or a resting thumb. */
(function(){
  function hydrated(){var s=document.getElementById('pricing');return s&&Object.keys(s).some(function(k){return k.indexOf('__react')===0})}
  function build(){
    if(document.getElementById('team'))return;
    var after=document.getElementById('shop')||document.getElementById('work');if(!after)return;
    var s=document.createElement('section');s.id='team';s.className='panel team';s.setAttribute('aria-labelledby','team-title');
    s.innerHTML='<div class="wrap team-in">'+
      '<a class="team-media" href="/about/" aria-label="Meet the team"><img src="/img/about/duo-2400.jpg" srcset="/img/about/duo-1200.jpg 1200w, /img/about/duo-2400.jpg 2400w" sizes="(max-width:800px) 100vw, 58vw" alt="Anthony DiGiovanni and Tanner Dilworth with the Irish Green Carrera GT" loading="lazy" draggable="false"><video src="/img/about/craft/desk.mp4" muted loop playsinline preload="none" disablepictureinpicture aria-hidden="true"></video></a>'+
      '<div class="team-copy"><h2 id="team-title" class="h3">Made by Hand</h2>'+
      '<p class="body">Anthony and Tanner work with every client directly, guiding each choice from the first conversation to the final specification. Every car is rendered by hand along the way, so you see exactly what you are building before the factory does. Not a single pixel is generated by AI.</p>'+
      '<a class="work-all team-link" href="/about/">Meet the team</a></div></div>';
    after.insertAdjacentElement('afterend',s);
    var m=s.querySelector('.team-media'),v=m.querySelector('video'),hover=matchMedia('(hover:hover)');
    function on(){m.classList.add('is-on');try{v.currentTime=0}catch(e){}var p=v.play();p&&p.catch&&p.catch(function(){})}
    function off(){m.classList.remove('is-on');setTimeout(function(){if(!m.classList.contains('is-on'))v.pause()},500)}
    m.addEventListener('mouseenter',function(){if(hover.matches)on()});
    m.addEventListener('mouseleave',function(){if(hover.matches)off()});
    m.addEventListener('touchstart',on,{passive:true});
    m.addEventListener('touchend',function(){setTimeout(off,250)},{passive:true});
    m.addEventListener('touchcancel',off,{passive:true});
    m.addEventListener('contextmenu',function(e){e.preventDefault()});
    if('IntersectionObserver' in window){var io=new IntersectionObserver(function(es){if(es[0].isIntersecting){v.preload='auto';io.disconnect()}},{rootMargin:'400px'});io.observe(m)}
  }
  var n=0;(function poll(){if(hydrated()||n>80){setTimeout(build,150);return}n++;setTimeout(poll,100)})();
})();
